SET MODE MariaDB;
DROP TABLE IF EXISTS match_user_guard;
DROP TABLE IF EXISTS match_participant;
DROP TABLE IF EXISTS "match";
DROP TABLE IF EXISTS facility_service_snapshot;

CREATE TABLE facility_service_snapshot (
    service_id BIGINT PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    location_name VARCHAR(100) NOT NULL,
    region VARCHAR(20) NOT NULL,
    is_free BOOLEAN,
    reservation_deadline_at TIMESTAMP,
    active BOOLEAN NOT NULL,
    source_updated_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE "match" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(50) NOT NULL,
    description VARCHAR(500),
    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP NOT NULL,
    max_participant INTEGER NOT NULL,
    status VARCHAR(10) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    skill_level VARCHAR(30) NOT NULL,
    sport_type VARCHAR(15) NOT NULL,
    gender_group VARCHAR(10) NOT NULL,
    service_id BIGINT NOT NULL,
    CONSTRAINT fk_match_service FOREIGN KEY (service_id)
        REFERENCES facility_service_snapshot(service_id)
);

CREATE TABLE match_participant (
    match_participant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    match_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    role VARCHAR(20) NOT NULL,
    CONSTRAINT fk_match_participant_match FOREIGN KEY (match_id)
        REFERENCES "match"(id),
    CONSTRAINT uk_match_participant_match_user UNIQUE (match_id, user_id)
);

CREATE TABLE match_user_guard (
    user_id BIGINT PRIMARY KEY,
    is_blocked BOOLEAN DEFAULT FALSE NOT NULL
);
